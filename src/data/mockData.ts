export const getArticlesByCategory = (articles: Article[], category: string): Article[] => {
  if (category === 'all') return articles;
  return articles.filter(a => a.category === category);
};

export const searchArticlesLocal = (articles: Article[], query: string): Article[] => {
  const lowerQuery = query.toLowerCase();
  return articles.filter(a =>
    a.title.toLowerCase().includes(lowerQuery) ||
    a.description.toLowerCase().includes(lowerQuery) ||
    a.source.toLowerCase().includes(lowerQuery) ||
    a.keywords.some(k => k.toLowerCase().includes(lowerQuery)) ||
    a.category.toLowerCase().includes(lowerQuery)
  );
};
